def normalize(text):
    """Uppercase, umlauts spelled out. Returns (text, dropped characters)."""
    text = (text.upper().replace("Ä", "AE").replace("Ö", "OE").replace("Ü", "UE")
            .replace("ß", "SS").replace("ẞ", "SS"))
    dropped = sorted({c for c in text if c not in GLYPHS and c != " "})
    text = "".join(c for c in text if c in GLYPHS or c == " ")
    return " ".join(text.split()), dropped          # no leading/trailing/double spaces


def layout(text):
    """The whole text as ONE polyline [(x, y), ...] in font units."""
    path = []
    x = 0.0
    for c in text:
        if c != " ":
            path += [(px + x, py) for px, py in GLYPHS[c]]
        x += ADVANCE
    return path
