"""Simple single-stroke vector font for the galvos.

Each glyph is a list of strokes; a stroke is a polyline of (x, y) points on a grid
4 wide and 6 high (y up, baseline 0). Dots are tiny strokes. Umlaut dots sit at y 7..7.4,
the comma tail goes down to -0.5. Advance per character is ADVANCE units.
Lowercase is drawn as uppercase.
"""

ADVANCE = 5.0               # 4 glyph + 1 gap

_O = [(1, 0), (0, 1), (0, 5), (1, 6), (3, 6), (4, 5), (4, 1), (3, 0), (1, 0)]
_P = [(0, 0), (0, 6), (3, 6), (4, 5), (4, 4), (3, 3), (0, 3)]
_A = [[(0, 0), (0, 4), (2, 6), (4, 4), (4, 0)], [(0, 3), (4, 3)]]
_U = [[(0, 6), (0, 1), (1, 0), (3, 0), (4, 1), (4, 6)]]
_DOTS = [[(1, 7), (1, 7.4)], [(3, 7), (3, 7.4)]]

GLYPHS = {
    " ": [],
    "A": _A,
    "B": [[(0, 0), (0, 6), (3, 6), (4, 5), (4, 4), (3, 3), (0, 3)],
          [(3, 3), (4, 2), (4, 1), (3, 0), (0, 0)]],
    "C": [[(4, 5), (3, 6), (1, 6), (0, 5), (0, 1), (1, 0), (3, 0), (4, 1)]],
    "D": [[(0, 0), (0, 6), (2, 6), (4, 4), (4, 2), (2, 0), (0, 0)]],
    "E": [[(4, 6), (0, 6), (0, 0), (4, 0)], [(0, 3), (3, 3)]],
    "F": [[(4, 6), (0, 6), (0, 0)], [(0, 3), (3, 3)]],
    "G": [[(4, 5), (3, 6), (1, 6), (0, 5), (0, 1), (1, 0), (3, 0), (4, 1), (4, 3), (2, 3)]],
    "H": [[(0, 0), (0, 6)], [(4, 0), (4, 6)], [(0, 3), (4, 3)]],
    "I": [[(1, 6), (3, 6)], [(2, 6), (2, 0)], [(1, 0), (3, 0)]],
    "J": [[(4, 6), (4, 1), (3, 0), (1, 0), (0, 1)]],
    "K": [[(0, 0), (0, 6)], [(4, 6), (0, 2)], [(1, 3), (4, 0)]],
    "L": [[(0, 6), (0, 0), (4, 0)]],
    "M": [[(0, 0), (0, 6), (2, 3), (4, 6), (4, 0)]],
    "N": [[(0, 0), (0, 6), (4, 0), (4, 6)]],
    "O": [_O],
    "P": [_P],
    "Q": [_O, [(2, 2), (4, 0)]],
    "R": [_P, [(2, 3), (4, 0)]],
    "S": [[(4, 5), (3, 6), (1, 6), (0, 5), (0, 4), (1, 3), (3, 3), (4, 2), (4, 1), (3, 0),
           (1, 0), (0, 1)]],
    "T": [[(0, 6), (4, 6)], [(2, 6), (2, 0)]],
    "U": _U,
    "V": [[(0, 6), (2, 0), (4, 6)]],
    "W": [[(0, 6), (1, 0), (2, 3), (3, 0), (4, 6)]],
    "X": [[(0, 0), (4, 6)], [(0, 6), (4, 0)]],
    "Y": [[(0, 6), (2, 3), (4, 6)], [(2, 3), (2, 0)]],
    "Z": [[(0, 6), (4, 6), (0, 0), (4, 0)]],
    "Ä": _A + _DOTS,
    "Ö": [_O] + _DOTS,
    "Ü": _U + _DOTS,
    "0": [_O, [(1, 1), (3, 5)]],
    "1": [[(1, 5), (2, 6), (2, 0)], [(1, 0), (3, 0)]],
    "2": [[(0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (0, 0), (4, 0)]],
    "3": [[(0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (3, 3), (4, 2), (4, 1), (3, 0), (1, 0), (0, 1)],
          [(1, 3), (3, 3)]],
    "4": [[(3, 0), (3, 6), (0, 2), (4, 2)]],
    "5": [[(4, 6), (0, 6), (0, 3), (3, 3), (4, 2), (4, 1), (3, 0), (0, 0)]],
    "6": [[(4, 5), (3, 6), (1, 6), (0, 5), (0, 1), (1, 0), (3, 0), (4, 1), (4, 2), (3, 3), (0, 3)]],
    "7": [[(0, 6), (4, 6), (1, 0)]],
    "8": [[(1, 3), (0, 4), (0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (3, 3), (1, 3), (0, 2), (0, 1),
           (1, 0), (3, 0), (4, 1), (4, 2), (3, 3)]],
    "9": [[(4, 3), (1, 3), (0, 4), (0, 5), (1, 6), (3, 6), (4, 5), (4, 1), (3, 0), (1, 0), (0, 1)]],
    "-": [[(1, 3), (3, 3)]],
    "+": [[(1, 3), (3, 3)], [(2, 2), (2, 4)]],
    "=": [[(1, 2), (3, 2)], [(1, 4), (3, 4)]],
    "_": [[(0, 0), (4, 0)]],
    ".": [[(2, 0), (2, 0.4)]],
    ",": [[(2, 1), (1.5, -0.5)]],
    ":": [[(2, 4), (2, 4.4)], [(2, 1), (2, 1.4)]],
    "!": [[(2, 6), (2, 2)], [(2, 0.4), (2, 0)]],
    "?": [[(0, 5), (1, 6), (3, 6), (4, 5), (4, 4), (2, 3), (2, 2)], [(2, 0.4), (2, 0)]],
    "'": [[(2, 6), (2, 5)]],
    "/": [[(0, 0), (4, 6)]],
    "*": [[(2, 1), (2, 5)], [(0.5, 2), (3.5, 4)], [(0.5, 4), (3.5, 2)]],
    "<": [[(4, 6), (0, 3), (4, 0)]],
    ">": [[(0, 6), (4, 3), (0, 0)]],
    "(": [[(3, 6), (2, 5), (2, 1), (3, 0)]],
    ")": [[(1, 6), (2, 5), (2, 1), (1, 0)]],
}

SUPPORTED = "".join(sorted(GLYPHS))


def normalize(text):
    """Uppercase, ß -> SS. Returns (text, list of unsupported characters, replaced by '?')."""
    text = text.replace("ß", "SS").upper()
    bad = sorted({c for c in text if c not in GLYPHS})
    return "".join(c if c in GLYPHS else "?" for c in text), bad


def layout(text):
    """Strokes for a line of text in font units: list of polylines [(x, y), ...]."""
    strokes = []
    for i, c in enumerate(text):
        dx = i * ADVANCE
        for stroke in GLYPHS[c]:
            strokes.append([(x + dx, y) for x, y in stroke])
    return strokes
